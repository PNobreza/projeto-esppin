CREATE VIEW VWN_SOCAMB_JUIZ_PROJ_CRIT_IND(
  CODIGO,
  COD_RODADA,
  COD_JUIZ,
  NME_JUIZ,
  COD_PROJETO,
  NME_PROJETO,
  COD_CRITERIO,
  DSC_CRITERIO,
  COD_INDICADOR,
  SGL_INDICADOR,
  DSC_INDICADOR
) AS
SELECT
 ( PCJ.COD_JUIZ || '.' || 
   CRT.COD_CRITERIO_REF_SOCAMB || '.' || 
   IND.COD_INDICADOR_REF_SOCAMB || '.' || 
   PCJ.COD_PROJETO ) AS CODIGO
, PCJ.COD_RODADA
, PCJ.COD_JUIZ
, 'JUIZ: '||UDF_COLLATEBR(UDF_UPPER(JZ.NME_JUIZ)) NME_JUIZ
, PCJ.COD_PROJETO
, 'PROJETO: '||UDF_COLLATEBR(UDF_UPPER(PRJ.NME_PROJETO)) NME_PROJETO
, CRT.COD_CRITERIO_REF_SOCAMB COD_CRITERIO
, 'Dimensão/Aspecto: ['||DMAS.DSC_NOME||']'||ASCII_CHAR(13)||ASCII_CHAR(10)||
  'Critério: ['||UDF_COLLATEBR(UDF_UPPER(CRT.DSC_NOME))||']'										
  AS DSC_CRITERIO
, IND.COD_INDICADOR_REF_SOCAMB COD_INDICADOR
, IND.DSC_ABREVIACAO SGL_INDICADOR
, 'INDICADOR: '||UDF_COLLATEBR(UDF_UPPER(IND.DSC_NOME)) DSC_INDICADOR
FROM TBN_SOCAMB_POND_JUIZPROJETO PCJ
LEFT JOIN TBN_RODADA RDD ON (PCJ.COD_RODADA = RDD.COD_RODADA)
LEFT JOIN TBN_JUIZ JZ ON (PCJ.COD_JUIZ = JZ.COD_JUIZ)
LEFT JOIN TBN_PROJETO PRJ ON (PCJ.COD_PROJETO = PRJ.COD_PROJETO)
LEFT JOIN TBN_CRITERIO_REF_SOCAMB CRT ON (PCJ.COD_CRITERIO = CRT.COD_CRITERIO_REF_SOCAMB)
LEFT JOIN TBN_DIMENSAO_ASPECTO_SOCAMB DMAS ON (DMAS.COD_DIMENSAO_ASPECTO_SOCAMB = CRT.COD_DIMENSAO_ASPECTO_SOCAMB)
LEFT JOIN TBN_INDICADOR_REF_SOCAMB IND ON (PCJ.COD_INDICADOR = IND.COD_INDICADOR_REF_SOCAMB)
ORDER BY PCJ.COD_RODADA ASC, 
		 PCJ.COD_JUIZ ASC, 
         CRT.COD_DIMENSAO_ASPECTO_SOCAMB ASC, 
         PCJ.COD_CRITERIO ASC,
         PCJ.COD_INDICADOR ASC
;





