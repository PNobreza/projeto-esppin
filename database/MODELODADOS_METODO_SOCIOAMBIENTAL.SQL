CREATE VIEW VWN_SOCAMB_PAINEL_PONDJZCRT(
  COD_RODADA,
  COD_JUIZ,
  NME_JUIZ,
  QTD_INDICADORES,
  LCMTOS_REALIZADOS,
  SITUACAO)
AS
SELECT
        XX.COD_RODADA,
        XX.COD_JUIZ,
        XX.NME_JUIZ,
        YY.TOTAL_CI AS QTD_INDICADORES,
        CASE
        	WHEN ( ZZ.TOTAL_LCMTOS = (-1*YY.TOTAL_CI) ) AND (ZZ.TOTAL_LCMTOS < 0) THEN CAST( -1 * ZZ.TOTAL_LCMTOS AS INTEGER )
            WHEN ( ZZ.TOTAL_LCMTOS < 0	) THEN CAST( -1 * ZZ.TOTAL_LCMTOS AS INTEGER )
        	ELSE CAST( YY.TOTAL_CI - ABS(ZZ.TOTAL_LCMTOS) AS INTEGER ) 
        END AS LCMTOS_REALIZADOS,		
        CASE
            WHEN ( ZZ.TOTAL_LCMTOS = (-1*YY.TOTAL_CI) ) THEN 'FALTA LANÇAR TUDO'
            WHEN ( ZZ.TOTAL_LCMTOS = YY.TOTAL_CI ) THEN 'LANÇADO COMPLETAMENTE'
            WHEN ( ZZ.TOTAL_LCMTOS < 0 ) THEN 'FALTA LANÇAR: ' || (-1*ZZ.TOTAL_LCMTOS)
        END AS SITUACAO            

FROM
(
	SELECT DISTINCT COD_RODADA, COD_JUIZ, NME_JUIZ
	FROM VWN_SOCAMB_POND_JUIZCRITERIO
) AS XX
JOIN (
	SELECT	COD_JUIZ,
			COUNT(VLR_IMPORTANCIA) AS TOTAL_CI
	FROM VWN_SOCAMB_POND_JUIZCRITERIO
	GROUP BY 1
) AS YY ON XX.COD_JUIZ = YY.COD_JUIZ
LEFT JOIN (
		SELECT	COD_JUIZ,
				-1 * COUNT(VLR_IMPORTANCIA) AS TOTAL_LCMTOS        
		FROM VWN_SOCAMB_POND_JUIZCRITERIO
		WHERE COD_IMPORTANCIA = -1
		GROUP BY 1
        UNION
		SELECT	COD_JUIZ,
				COUNT(VLR_IMPORTANCIA) AS TOTAL_LCMTOS        
		FROM 	VWN_SOCAMB_POND_JUIZCRITERIO
		WHERE	COD_IMPORTANCIA > -1
		AND 	COD_JUIZ NOT IN (
								SELECT DISTINCT COD_JUIZ
								FROM VWN_SOCAMB_POND_JUIZCRITERIO
								WHERE COD_IMPORTANCIA = -1
								)
		GROUP BY 1
) AS ZZ ON XX.COD_JUIZ = ZZ.COD_JUIZ
;

