DROP VIEW VWN_SOC_POND_JUIZCRITERIO;

CREATE VIEW VWN_SOC_POND_JUIZCRITERIO(
  COD_RODADA,
  DSC_RODADA,
  COD_JUIZ,
  ABV_JUIZ,
  NME_JUIZ,
  COD_CRITERIO,
  SGL_CRITERIO,
  DSC_CRITERIO,
  COD_INDICADOR,
  SGL_INDICADOR,
  DSC_INDICADOR,
  COD_IMPORTANCIA,
  VLR_IMPORTANCIA,
  DSC_IMPORTANCIA)
AS
SELECT
  pcj.cod_rodada
, rdd.dsc_rodada

, pcj.cod_juiz
, jz.abv_juiz
, jz.nme_juiz

, crt.COD_CRITERIO_REF_SOCIAL cod_criterio
, crt.DSC_ABREVIACAO
, UDF_COLLATEBR(UDF_UPPER(crt.dsc_nome)) dsc_criterio

, ind.COD_INDICADOR_REF_SOCIAL cod_indicador
, ind.DSC_ABREVIACAO sgl_indicador
, UDF_COLLATEBR(UDF_UPPER(ind.dsc_nome)) dsc_indicador

, pcj.COD_IMPORTANCIA
, imp.vlr_importancia
, imp.dsc_importancia
FROM TBN_SOC_PONDERACAO_JUIZCRITERIO pcj
LEFT JOIN tbn_rodada rdd ON (pcj.cod_rodada = rdd.cod_rodada)
LEFT JOIN tbn_criterio_ref_SOCIAL crt ON (pcj.cod_criterio = crt.COD_CRITERIO_REF_SOCIAL)
LEFT JOIN TBN_INDICADOR_REF_SOCIAL ind ON (pcj.cod_indicador = ind.COD_INDICADOR_REF_SOCIAL)
LEFT JOIN tbn_juiz jz ON (pcj.cod_juiz = jz.cod_juiz)
LEFT JOIN tbn_importancia imp ON (pcj.cod_importancia = imp.cod_importancia AND imp.grp_importancia = 'escores')
;

