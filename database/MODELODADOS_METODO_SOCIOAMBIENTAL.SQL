  DSC_CRITERIO VARCHAR(250) CHARACTER SET ISO8859_1,
  COD_INDICADOR INTEGER,
  SGL_INDICADOR VARCHAR(20) CHARACTER SET ISO8859_1,
  DSC_INDICADOR VARCHAR(150) CHARACTER SET ISO8859_1,
  VLR_PONDERACAO_CALCULADA NUMERIC(18, 2),
  VLR_PONDERACAO_CALC_RF NUMERIC(18, 2))
AS
BEGIN
FOR
	SELECT
	  PSP.COD_RODADA
	, RDD.DSC_RODADA
	
	, PSP.COD_PROJETO
	, PRJ.SGL_PROJETO
	, PRJ.NME_PROJETO
	
	, PSP.COD_CRITERIO
	, 'Dimensão/Aspecto: ['||DMAS.DSC_NOME||']'||ASCII_CHAR(13)||ASCII_CHAR(10)||
	  'Critério: ['||UDF_COLLATEBR(UDF_UPPER(CRT.DSC_NOME))||']' AS DSC_CRITERIO
	
	, PSP.COD_INDICADOR
	, IND.DSC_ABREVIACAO SGL_INDICADOR
	, UDF_COLLATEBR(UDF_UPPER(IND.DSC_NOME)) AS DSC_INDICADOR	
		
	, PSP.VLR_PONDERACAO AS VLR_PONDERACAO_CALCULADA
	, PSPRF.VLR_DECISAO_FINAL AS VLR_PONDERACAO_CALC_RF
	
	FROM TBN_SOCAMB_POND_SISPROJ_GRD PSP
	JOIN TBN_SOCAMB_POND_SISPROJ_RF PSPRF ON (	PSP.COD_PROJETO = PSPRF.COD_PROJETO AND 
												PSPRF.FLG_TIPO_EQUACAO = :PARAM_FLG_TIPO_EQUACAO AND
												PSPRF.COD_RODADA = :PARAM_COD_RODADA )

	LEFT JOIN TBN_RODADA RDD ON (PSP.COD_RODADA = RDD.COD_RODADA)

	LEFT JOIN TBN_PROJETO PRJ ON (PSP.COD_PROJETO = PRJ.COD_PROJETO)
	
	LEFT JOIN TBN_CRITERIO_REF_SOCAMB CRT ON (PSP.COD_CRITERIO = CRT.COD_CRITERIO_REF_SOCAMB)

	LEFT JOIN TBN_DIMENSAO_ASPECTO_SOCAMB DMAS ON (DMAS.COD_DIMENSAO_ASPECTO_SOCAMB = CRT.COD_DIMENSAO_ASPECTO_SOCAMB)
	
	LEFT JOIN TBN_INDICADOR_REF_SOCAMB IND ON (PSP.COD_INDICADOR = IND.COD_INDICADOR_REF_SOCAMB)
	
	WHERE 	PSP.FLG_TIPO_EQUACAO = :PARAM_FLG_TIPO_EQUACAO
	AND		PSP.COD_RODADA = :PARAM_COD_RODADA

	ORDER BY PSP.COD_PROJETO, PSP.COD_CRITERIO, PSP.COD_INDICADOR

	INTO :COD_RODADA, :DSC_RODADA, 
	     :COD_PROJETO, :SGL_PROJETO, :NME_PROJETO , 
		 :COD_CRITERIO, :DSC_CRITERIO , 
		 :COD_INDICADOR, :SGL_INDICADOR, :DSC_INDICADOR , 
		 :VLR_PONDERACAO_CALCULADA, :VLR_PONDERACAO_CALC_RF
    
DO
SUSPEND;
END ^
SET TERM ; ^
COMMIT WORK;


