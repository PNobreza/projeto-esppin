CREATE VIEW VWN_SOCAMB_JUIZ_CRIT_IND(
  CODIGO,
  COD_RODADA,
  COD_JUIZ,
  NME_JUIZ,
  COD_CRITERIO,
  DSC_CRITERIO,
  COD_INDICADOR,
  DSC_INDICADOR)
AS
SELECT 
(rdd.cod_juiz || '.' || crtref.COD_CRITERIO_REF_SOCAMB || '.' || indref.COD_INDICADOR_REF_SOCAMB ) Codigo
, rdd.cod_rodada
, rdd.cod_juiz
, 'Juiz: '||UDF_COLLATEBR( UDF_UPPER(jz.nme_juiz) ) nme_juiz
, crtref.COD_CRITERIO_REF_SOCAMB cod_criterio
, 'Dimensão/Aspecto: ['||DMAS.DSC_NOME||']'||ASCII_CHAR(13)||ASCII_CHAR(10)||
  'Critério: ['||UDF_COLLATEBR(UDF_UPPER(crtref.DSC_NOME))||']'										
  AS dsc_criterio
, indref.COD_INDICADOR_REF_SOCAMB cod_indicador
, 'Indicador: '||UDF_COLLATEBR(UDF_UPPER(indref.dsc_nome)) dsc_indicador

FROM RLN_JUIZES_RODADA rdd 
JOIN TBN_JUIZ jz ON (rdd.COD_JUIZ = jz.COD_JUIZ)
JOIN RLN_CRITERIOS_SOCAMB_RODADA crtrdd ON (rdd.cod_rodada = crtrdd.cod_rodada)
JOIN TBN_CRITERIO_REF_SOCAMB crtref ON (crtrdd.COD_CRITERIO_SOCAMB = crtref.COD_CRITERIO_REF_SOCAMB)
LEFT JOIN TBN_DIMENSAO_ASPECTO_SOCAMB DMAS ON (DMAS.COD_DIMENSAO_ASPECTO_SOCAMB = crtref.COD_DIMENSAO_ASPECTO_SOCAMB)
JOIN TBN_INDICADOR_REF_SOCAMB indref ON (crtref.COD_CRITERIO_REF_SOCAMB = indref.COD_CRITERIO_REF_SOCAMB)
ORDER BY rdd.cod_rodada, nme_juiz , cod_criterio, cod_indicador
;
